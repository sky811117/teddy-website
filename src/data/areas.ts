export type StatSegmentKey = "tower_resale" | "tower_new" | "midrise" | "apartment" | "townhouse";

export type StatSegment = {
  key: StatSegmentKey;
  label: string;
  n: number;
  median: number; // 萬元/坪
  p25: number;
  p75: number;
  smallSample: boolean; // 筆數 < 10
  imputedShare: number; // 車位價未拆分、用同區同類車位中位數推估的比例（%）
};

type DistrictStats = {
  n: number;
  under5mShare: number | null;
  segments: StatSegment[];
};

type AreaStatsFile = {
  generatedAt: string;
  period: { label: string; rocLabel: string; start: string; end: string; quarters: string[] };
  dbMaxDealDate: string;
  source: string;
  method: string;
  districts: Record<string, DistrictStats>;
};

const areaStats = areaStatsJson as unknown as AreaStatsFile;

// 區域數據的資料期與來源（[district].astro 的數據表表頭 / 來源列、/areas/ 總覽、seoSections 都引用）
export const AREA_DATA_PERIOD = `成交日 ${areaStats.period.label}`;
export const AREA_DATA_SOURCE = `${areaStats.source}，站方逐筆統計`;
export const AREA_STATS_META = {
  start: areaStats.period.start,
  end: areaStats.period.end,
  rocLabel: areaStats.period.rocLabel,
  dbMaxDealDate: areaStats.dbMaxDealDate,
  generatedAt: areaStats.generatedAt,
  source: areaStats.source,
  method: areaStats.method,
};
// seoSections／FAQ 引用數字時統一掛這一段
const AREA_CITE = `（資料期：${AREA_DATA_PERIOD}，來源 ${AREA_DATA_SOURCE}）`;

export function getDistrictStats(district: string): DistrictStats | undefined {
  return areaStats.districts[district];
}

// 頁面數據表用：該區有數字的分群（筆數 < 5 的 build-area-stats.py 已經不輸出）
export function getAreaStats(area: { districtMatch: string[] }): StatSegment[] {
  return getDistrictStats(area.districtMatch[0])?.segments ?? [];
}

const SEG_PROSE: Record<StatSegmentKey, string> = {
  tower_resale: "屋齡 3 年以上的中古大樓",
  tower_new: "屋齡未滿 3 年的新成屋大樓",
  midrise: "華廈",
  apartment: "公寓",
  townhouse: "透天厝",
};
const fmt = (n: number) => n.toFixed(1);
// 「北屯區」→「北屯」；「中區」「北區」這種兩個字的保留原名（不然會變成「中近 4 季」）
const shortDistrict = (d: string) => (d.length > 2 ? d.replace(/區$/, "") : d);
const findSeg = (district: string, key: StatSegmentKey) =>
  getDistrictStats(district)?.segments.find(s => s.key === key);
const segPhrase = (s: StatSegment) =>
  `${SEG_PROSE[s.key]}約 ${fmt(s.median)} 萬/坪（${s.n} 筆${s.smallSample ? "，樣本少" : ""}）`;

// 區域行情段落：有數字就列；該區資料不夠就退回不寫數字的說法
function priceParagraph(district: string, keys: StatSegmentKey[]): string {
  const segs = keys
    .map(k => findSeg(district, k))
    .filter((s): s is StatSegment => !!s);
  if (segs.length === 0) {
    return `${shortDistrict(district)}近 4 季列入統計的實價登錄成交太少，這裡不列區域單價；比價一律拉同社區、同屋齡、同坪數的成交來對。📌 資料來源：內政部實價登錄`;
  }
  return `${shortDistrict(district)}近 4 季的扣車位成交單價中位數：${segs.map(segPhrase).join("、")}${AREA_CITE}。`;
}

// 兩區同產品對照（只列兩邊都有數字的分群；只給數字，不下「便宜多少」的結論，免得資料一換就說錯）
function compareSentence(a: string, b: string, keys: StatSegmentKey[]): string {
  const parts = keys.flatMap(k => {
    const x = findSeg(a, k);
    const y = findSeg(b, k);
    if (!x || !y) return [];
    return [`${SEG_PROSE[k]}${shortDistrict(a)}約 ${fmt(x.median)}、${shortDistrict(b)}約 ${fmt(y.median)} 萬/坪`];
  });
  return parts.length > 0
    ? `近 4 季扣車位成交單價中位數：${parts.join("；")}${AREA_CITE}。`
    : "";
}

// 單一分群＋中間一半（P25～P75）
function spreadSentence(district: string, key: StatSegmentKey): string {
  const s = findSeg(district, key);
  if (!s) return "";
  return `${shortDistrict(district)}近 4 季${SEG_PROSE[key]}扣車位成交單價中位數約 ${fmt(s.median)} 萬/坪，但中間一半的成交就分布在 ${fmt(s.p25)}～${fmt(s.p75)} 萬/坪${AREA_CITE}。`;
}

// 總價未滿 500 萬的成交比例（含車位總價，住家用四種型態）；緊接在 priceParagraph 後面時 withCite=false，免得同段掛兩次來源
function under5mSentence(district: string, withCite = true): string {
  const share = getDistrictStats(district)?.under5mShare;
  if (share == null) return "";
  return `近 4 季列入統計的住家成交裡，總價未滿 500 萬的約佔 ${share}%${withCite ? AREA_CITE : "（同一資料期與口徑）"}。`;
}

